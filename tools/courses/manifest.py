"""Writes docs/COURSE_MANIFEST.md from the course data and a fresh solver run.

  python tools/courses/manifest.py

For each main course it runs client/tests/course_report.gd (headless; no window opens) to get
the solver bot's shot count per hole, then writes the summary, the per-hole tables (name, par,
solver shots, design notes) and the reference-fidelity notes. Edit the text here, not the .md.
"""
import json
import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
GODOT = os.path.join(ROOT, "tools", "godot", "Godot_v4.7.2-stable_win64_console.exe")
COURSES = ["golf_land", "beach_land", "sticky_zone", "snow_field", "gravity_lab", "spin_land"]

# Verified SSG3 details each rebuilt course keeps, and how the repo proves them.
VERIFIED = {
    "golf_land": "",
    "beach_land": "Pars 5-5-5-5-4-4-4-4-5 are SSG3's (verified). Hole 4 is aceable with the plain ball: "
                  "`tests/ace_search.gd -- --course beach_land --hole 3` finds 38 aces in an 8601-shot sweep (0.44%).",
    "sticky_zone": "Hole 7 can be completed without touching goo: "
                   "`tests/no_touch_check.gd -- --course sticky_zone --hole 6 --material sticky` passes in 5 shots "
                   "(the same check on hole 3, which needs the goo ceiling, correctly fails).",
    "snow_field": "Hole 4 can be aced touching only the green: "
                  "`tests/ace_search.gd -- --course snow_field --hole 3 --only grass` finds 31 of 8601 tee shots (0.36%). "
                  "SSG3's Snow Field unlocks the Ice Ball, which freezes this course's lakes.",
    "gravity_lab": "SSG3's Gravity Lab unlocks the Anti-Grav Ball. SSG3's hole 6 \"Nil Score\" achievement relies on a "
                   "scoring rule that is not documented, so it is not reproduced.",
    "spin_land": "The course can be finished under par without spin: the solver bot never uses spin and finishes well under par.",
}


def solver_shots(cid):
    out = os.path.join(tempfile.gettempdir(), "manifest_%s.json" % cid)
    subprocess.run([GODOT, "--headless", "--path", os.path.join(ROOT, "client"), "--script", "res://tests/course_report.gd",
                    "--", "--course", cid, "--out", out], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    rep = json.load(open(out, encoding="utf-8"))
    return {h["id"]: (int(h["strokes"]) if h.get("holed") else None) for h in rep["holes"]}


def main():
    lines = ["# Course Manifest", "",
             "These are the six main courses as implemented (`client/data/courses/*.json`, authored in "
             "`tools/courses/<id>.py`). This file is generated by `tools/courses/manifest.py`.", "",
             "Every hole is completed by the solver bot with the plain ball and no spin (`client/tests/test_playable.gd`). "
             "It also passes the geometry and random-shot robustness checks (`client/tests/test_sim.gd`).", "",
             "## Reference fidelity", "",
             "The six courses follow the order and themes of Super Stickman Golf 3's first six courses: Golf Land, Beach Land, "
             "Sticky Zone, Snow Field, Gravity Lab and Spin Land (`docs/COURSE_REFERENCE.md` records the research).", "",
             "- **Pars.** Beach Land uses SSG3's verified per-hole pars. SSG3's pars for Sticky Zone, Snow Field, Gravity Lab "
             "and Spin Land are not available, so those are design pars (`\"parSource\": \"design\"` in the data), set so a "
             "near-perfect player finishes about one under per hole, as SSG3's medals (bronze par, silver -5, gold -10) imply.",
             "- **Layouts.** SSG3's hole geometry is not available (and is the developer's proprietary work), so every layout "
             "is original. Each course is built around its SSG3 mechanic, and keeps the verified per-hole details listed below.",
             "- **Attached terrain.** Rebuilt courses are built with `strict=True`: every platform, ceiling and ledge must "
             "connect to the ground (`lib.check_attached`), outlines may not fold back, and floating decor types are refused. "
             "Ceilings are overhangs from a cliff or wall; lab ceilings rest on the room's walls.",
             "- **Records.** Each rebuilt course has `\"layout\": 2`. Solo bests and medals from the old layouts are archived "
             "under `legacy` in the player's records, not compared with the new holes; completion (ball unlocks) carries over.",
             "", "## Summary", "",
             "| # | Course | Difficulty | Holes | Par | Par source | Solver total | Core mechanic |",
             "|---|---|---|---|---|---|---|---|"]
    sections = []
    for cid in COURSES:
        c = json.load(open(os.path.join(ROOT, "client", "data", "courses", cid + ".json"), encoding="utf-8"))
        shots = solver_shots(cid)
        par = sum(int(h["par"]) for h in c["holes"])
        total = sum(v for v in shots.values() if v)
        src = {"ssg3": "SSG3 (verified)", "design": "design"}.get(c.get("parSource", ""), "original course")
        lines.append("| %d | %s (`%s`) | %s | %d | %d | %s | %d | %s |" % (c["order"], c["name"], cid, c["difficulty"],
                     len(c["holes"]), par, src, total, c["mechanic"]))
        sec = ["", "## %d. %s" % (c["order"], c["name"]), ""]
        if VERIFIED.get(cid):
            sec += [VERIFIED[cid], ""]
        sec += ["| Hole | Name | Par | Solver | Design |", "|---|---|---|---|---|"]
        for i, h in enumerate(c["holes"]):
            s = shots.get(h["id"])
            sec.append("| %d | %s | %d | %s | %s |" % (i + 1, h["name"], h["par"], s if s else "not holed", h.get("notes", "")))
        sections += sec
    lines.append("")
    lines.append("Total: **%d playable holes.**" % (9 * len(COURSES)))
    lines += ["", "Online Blitz matches draw holes from all six courses (`GameData.POOL_ID` = `blitz_pool`), and each hole "
              "keeps its own world theme. A private room can instead pick one course id. The practice-only Physics Lab "
              "(`physics_lab`) is excluded from both. The old id `sunny_meadows` resolves to Golf Land, so existing data stays valid."]
    lines += sections
    lines += ["", "## Course data per hole", "", "Each hole has:",
              "- tee spawn (up to 6 balls are spread across it automatically, or placed by an optional `spawns` list);",
              "- cup;", "- bounds (camera limits and out of bounds);", "- terrain polygons with per-edge materials;",
              "- hazard zones (water, acid, lava);", "- gravity fields;", "- decor;", "- par;", "- designer notes.", "",
              "Moving obstacles are not implemented yet; no hole uses them.", "",
              "## Tools", "",
              "- `python tools/courses/check.py <course> [--hole N] [--out DIR]`: rebuild a course and render review maps "
              "with the solver's shot paths (headless).",
              "- `tests/ace_search.gd`: fine sweep of tee shots that hole in one (`--only <material>` restricts contact).",
              "- `tests/no_touch_check.gd`: proves a hole can be finished without touching a material.",
              "- `python tools/courses/manifest.py`: regenerates this file.", "",
              "## Not yet done", "",
              "- **Collectibles.** There are no optional collectibles or alternative objectives yet. The format can carry them.",
              "- **SSG3 geometry.** Layouts are original (see Reference fidelity). Exact SSG3 holes would need authorised "
              "reference material for every hole.", ""]
    path = os.path.join(ROOT, "docs", "COURSE_MANIFEST.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", path)


if __name__ == "__main__":
    main()
